// 📖 Il dizionario: parole italiane vere (rare, antiche, dialettali o tecniche) con la loro definizione vera,
// e quello che vede ogni telefono

export interface DizOption {
  text: string;
  mine: boolean; // l'ho scritta io (non posso votarla)
  // solo nella rivelazione
  real?: boolean;
  authors?: string[];
  voters?: string[];
  marked?: boolean; // chi guida ha detto che era giusta anche questa
}

export interface DizionarioView {
  stage: 'WRITE' | 'VOTE' | 'REVEAL' | 'END';
  order: string[];
  round: number;
  rounds: number;
  word: string;
  cat: string; // es. "sostantivo maschile"
  stageEndsAt: number | null;
  revealAt: number | null; // inizio della rivelazione (ora del server): le carte si girano una alla volta
  written: string[]; // chi ha già scritto
  myDef: string | null;
  options: DizOption[];
  voted: string[]; // chi ha votato (non cosa)
  myVote: number | null;
  real: string | null; // la definizione vera (dalla rivelazione)
  exact: string[]; // chi ha scritto la definizione giusta (riconosciuta da sola)
  scores: Record<string, number>;
  gained: Record<string, number>; // punti di questo round (rivelazione)
}

