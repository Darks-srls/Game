export type EmojiCat = 'film' | 'canzone' | 'proverbio' | 'personaggio' | 'serie' | 'cartone';

export const EMOJI_CATS: Record<EmojiCat, string> = {
  film: '🎬 Film',
  canzone: '🎵 Canzone italiana',
  proverbio: '💬 Proverbio o modo di dire',
  personaggio: '🦸 Personaggio',
  serie: '📺 Serie TV',
  cartone: '🧸 Cartone animato',
};

export interface EmojiItem {
  e: string; // la fila di emoji
  a: string; // la risposta (si mostra così)
  c: EmojiCat;
  alt: string[]; // altre risposte accettate
}

// cosa vede ciascun giocatore (la risposta arriva solo a chi l'ha già indovinata o alla rivelazione)
export interface EmojiView {
  stage: 'READY' | 'PLAY' | 'REVEAL' | 'END';
  order: string[];
  scores: Record<string, number>;
  gained: Record<string, number>; // punti presi in questo round
  round: number;
  rounds: number;
  stageEndsAt: number | null;
  startedAt: number | null; // quando sono comparse le emoji (per i tempi)
  nextHintAt: number | null;
  emoji: string | null; // null mentre ci si prepara
  hint: number; // aiutini usciti: 0, 1, 2
  cat: EmojiCat | null; // dal primo aiutino
  mask: (string | null)[] | null; // un elemento per carattere: lettera scoperta, null = nascosta, spazi e segni restano
  solved: { id: string; ms: number; points: number }[]; // in ordine di arrivo
  me: { solved: boolean; tries: number; last: string | null; verdict: 'NO' | 'CLOSE' | null; waitUntil: number };
  answer: string | null;
  history: { e: string; a: string; first: string | null }[]; // solo a fine partita
}

