// 🔟 Da 1 a 10: i temi con la loro scala e quello che vede ogni telefono

export interface Scala10Theme {
  t: string; // il tema
  lo: string; // cosa vuol dire 1
  hi: string; // cosa vuol dire 10
}

// cosa vede ciascun giocatore: il numero segreto solo il suo, gli autori delle risposte solo alla rivelazione
export interface Scala10View {
  stage: 'WRITE' | 'ORDER' | 'REVEAL' | 'END';
  order: string[];
  round: number;
  rounds: number;
  captain: string;
  theme: Scala10Theme;
  stageEndsAt: number | null;
  writers: string[]; // chi deve scrivere in questo round
  written: string[]; // chi ha già scritto
  myNumber: number | null; // il mio numero segreto (null per il capitano)
  myAnswer: string | null;
  answers: { id: number; text: string; mine: boolean }[]; // dall'ordine in poi: anonime e mescolate
  arrange: number[]; // fila scelta dal capitano (id delle risposte), dalla più bassa alla più alta
  result: { id: number; text: string; by: string; n: number; ok: boolean }[] | null; // rivelazione, nell'ordine del capitano
  skipped: boolean; // round saltato: troppo poche risposte
  lives: number;
  maxLives: number;
  score: number;
  maxScore: number;
  gained: number; // punti di questo round
  lost: number; // vite perse in questo round
  history: { captain: string; theme: string; ok: number; total: number }[];
}

