// cosa vede ciascun giocatore (le stime degli altri solo quando si scommette)
export interface StimaView {
  stage: 'GUESS' | 'BET' | 'REVEAL' | 'END';
  order: string[];
  round: number; // da 1
  rounds: number;
  question: string;
  unit: string;
  spicy: boolean;
  stageEndsAt: number | null;
  guessed: string[]; // chi ha già scritto (non cosa)
  myGuess: number | null;
  slots: StimaSlot[]; // dalla fase delle scommesse
  chips: number; // fiches a testa per round
  myBets: number[]; // indici delle caselle su cui ho messo le mie fiches
  betDone: string[]; // chi ha piazzato tutte le fiches
  bets: Record<string, number[]> | null; // le fiches di tutti (dalla rivelazione)
  answer: number | null; // dalla rivelazione
  win: number | null; // casella vincente (null = nessuna stima)
  gained: Record<string, number>;
  scores: Record<string, number>;
  history: { q: string; a: number; u: string }[]; // a fine partita
}

